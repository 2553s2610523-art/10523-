import streamlit as st

# 웹앱 제목
st.title("🥗 스마트 다이어트 식단 가이드")
st.subheader("지치지 않는 체중 감량을 위한 식단 법칙")

# 구분선
st.divider()

# 사이드바 메뉴 구성
goal = st.sidebar.selectbox(
    "나의 다이어트 목표를 선택하세요:",
    ["정석 다이어트 (체지방 감량)", "급찐급빠 (단기 감량)", "유지어터 (체중 유지)"]
)

# 선택한 목표에 따른 내용 출력
if goal == "정석 다이어트 (체지방 감량)":
    st.header("🍏 지속 가능한 정석 식단")
    st.write("1. **탄단지 밸런스:** 매 끼니 [현미밥/고구마(탄)] + [닭가슴살/생선/두부(단)] + [야채(지질/식이섬유)]를 챙기세요.")
    st.write("2. **포만감 유지:** 식이섬유가 풍부한 채소를 먼저 먹으면 과식을 막을 수 있습니다.")
    st.write("3. **일반식 활용:** 하루 한 끼는 일반식을 먹되, 밥 양을 평소의 반으로 줄이세요.")

elif goal == "급찐급빠 (단기 감량)":
    st.header("🔥 급하게 찐 살 탈출 식단")
    st.write("1. **국물 및 소스 제한:** 나트륨은 수분을 잡아두어 부기를 만듭니다. 건더기 위주로 드세요.")
    st.write("2. **간헐적 단식 활용:** 저녁 식사 후 다음 날 아침까지 16시간 공복을 유지해 보세요.")
    st.write("3. **정제 탄수화물 끊기:** 밀가루, 설탕, 액상과당은 며칠간 완전히 멀리하는 것이 좋습니다.")

elif goal == "유지어터 (체중 유지)":
    st.header("🥑 요요 없는 유지 식단")
    st.write("1. **기초대사량 맞추기:** 너무 적게 먹으면 대사가 망가집니다. 내 기초대사량만큼은 건강하게 섭취하세요.")
    st.write("2. **치팅데이의 규칙:** 일주일에 한 번 원하는 음식을 먹되, 폭식이 아닌 '적당한 한 끼'로 즐기세요.")
    st.write("3. **대체 식품 찾기:** 제로 음료, 알룰로스, 두부면 등 칼로리가 낮은 대체재를 적극 활용하세요.")

# 응원 문구
st.sidebar.info("건강한 식단이 아름다운 몸을 만듭니다! ✨")
