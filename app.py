import streamlit as st

# 웹앱 제목
st.title("🏋️‍♂️ 운동 잘하는 방법 꿀팁 앱")
st.subheader("초보자를 위한 운동 성공 방정식")

# 구분선
st.divider()

# 사이드바 메뉴 구성
category = st.sidebar.selectbox(
    "알고 싶은 운동 분야를 선택하세요:",
    ["근력 트레이닝(웨이트)", "유산소 운동", "스트레칭 및 회복"]
)

# 선택한 카테고리에 따른 내용 출력
if category == "근력 트레이닝(웨이트)":
    st.header("💪 근력 트레이닝의 핵심")
    st.write("1. **점진적 과부하:** 지난주보다 무게나 횟수를 조금씩 늘리세요.")
    st.write("2. **바른 자세 우선:** 무게보다 부상 방지가 먼저입니다. 거울이나 영상을 활용하세요.")
    st.write("3. **큰 근육 위주:** 가슴, 등, 하체 같은 대근육 위주로 루틴을 짜세요.")

elif category == "유산소 운동":
    st.header("🏃‍♂️ 유산소 운동의 핵심")
    st.write("1. **꾸준한 빈도:** 주 3~4회, 최소 30분 이상 지속하는 것이 좋습니다.")
    st.write("2. **적정 심박수:** 옆 사람과 약간 숨차게 대화할 수 있는 강도가 이상적입니다.")
    st.write("3. **지루함 탈피:** 러닝, 사이클, 수영 등 즐길 수 있는 종목을 찾으세요.")

elif category == "스트레칭 및 회복":
    st.header("🧘‍♂️ 스트레칭 및 회복의 핵심")
    st.write("1. **운동 전/후 구분:** 운동 전에는 동적 스트레칭, 운동 후에는 정적 스트레칭!")
    st.write("2. **충분한 수면:** 근육은 운동할 때가 아니라 잘 때 자랍니다. 하루 7-8시간 수면 필수.")
    st.write("3. **수분 섭취:** 운동 중에는 물론, 평소에도 물을 자주 마셔주세요.")

# 응원 문구
st.sidebar.success("오늘도 득근하세요! 🔥")
